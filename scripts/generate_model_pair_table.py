OUT_BASELINE = ROOT / "paper_assets/tables/baseline_performance.tex"
OUT_PRESSURE = ROOT / "paper_assets/tables/model_pair_pressure.tex"

POLICIES = ["NoSpec", "FixedK-1", "FixedK-3", "TETRIS-Proxy", "SpecSched"]
MODEL_PAIRS = [
    {
        "name": "Qwen2.5",
        "target": "Qwen2.5-1.5B",
        "draft": "Qwen2.5-0.5B",
        "root": ROOT / "results/tpds_multiseed_second_model/processed",
        "detector_root": ROOT / "results/detector_safety/qwen15b",
    },
    {
        "name": "SmolLM2",
        "target": "SmolLM2-1.7B",
        "draft": "SmolLM2-135M",
        "root": ROOT / "results/tpds_multiseed_smol_model/processed",
        "detector_root": ROOT / "results/detector_safety/smol",
    },
    {
        "name": "Pythia",
        "target": "Pythia-2.8B",
        "draft": "Pythia-160M",
        "root": ROOT / "results/tpds_multiseed_pythia_model/processed",
        "detector_root": ROOT / "results/detector_safety/pythia",
    },
]


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def fmt_mean_std(row: dict[str, str], mean_key: str, std_key: str) -> str:
    mean = float(row[mean_key])
    std = float(row[std_key])
    return f"{mean:.1f}$\\pm${std:.1f}"


def fmt_lift(value: float) -> str:
    return f"{value:+.1f}\\%"


def fmt_lift_row(values: list[float]) -> str:
    return " / ".join(fmt_lift(value) for value in values)


def color_lift(value: float, significant: bool = True) -> str:
    rendered = fmt_lift(value)
    if rendered.startswith("-"):
        rendered = "$-$" + rendered[1:]
    if significant and value > 0:
        return f"\\pos{{{rendered}}}"
    return f"\\bad{{{rendered}}}"


def neutral_lift(value: float) -> str:
    rendered = fmt_lift(value)
    if rendered.startswith("-"):
        rendered = "$-$" + rendered[1:]
    return f"\\secondb{{{rendered}}}"


def detector_cell(decision: str) -> str:
    if decision == "ON":
        return "\\dON{ON}"
    if decision == "OFF":
        return "\\dOFF{OFF}"
    return decision


def best_policy(rows: dict[str, dict[str, str]]) -> str:
    return max(POLICIES, key=lambda policy: float(rows[policy]["goodput_tok_s_mean"]))


def detector_decision(pair: dict) -> str:
    decisions = []
    for seed_dir in sorted(pair["detector_root"].glob("seed_*")):
        path = seed_dir / "processed" / "scheduler_all_summary.csv"
        if not path.exists():
            continue
        for row in read_csv(path):
            if row.get("policy") == "SpecSched-Safe":
                decisions.append(str(row.get("x_detector_decision", "")))
    if not decisions:
        return ""
    if all(decision == "speculate" for decision in decisions):
        return "ON"
    if all(decision == "fallback_nospec" for decision in decisions):
        return "OFF"
    return "Mixed"


def build_table() -> str:
    lines = [
        "% Auto-generated by scripts/generate_model_pair_table.py. Do not edit values by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Model-pair sensitivity and safe fallback at $N=16$ across three seeds. Values are SLO-aware goodput in tok/s ($\\uparrow$), mean$\\pm$std. Detector color gives the warm-up decision; the safe-fallback column reports paired lift against NoSpec.}",
        "\\label{tab:model-pair-performance}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.5pt}",
        "\\renewcommand{\\arraystretch}{1.12}",
        "\\begin{tabular}{@{}p{0.10\\textwidth}p{0.15\\textwidth}ccccc cc@{}}",
        "\\toprule",
        "\\multirow{2}{*}{Family} & \\multirow{2}{*}{Target / draft} &",
        "\\multicolumn{3}{c}{Baselines ($\\uparrow$)} &",
        "\\multicolumn{2}{c}{\\system{} variants ($\\uparrow$)} &",
        "\\multicolumn{2}{c}{Safety outcome} \\\\",
        "\\cmidrule(lr){3-5}\\cmidrule(lr){6-7}\\cmidrule(l){8-9}",
        " & & NoSpec & BestFixed & TETRIS-Proxy & plain & safe & Detector & Safe vs NoSpec \\\\",
        "\\midrule",
    ]
    for pair in MODEL_PAIRS:
        summary_rows = {
            row["policy"]: row
            for row in read_csv(pair["root"] / "main_multiseed_summary.csv")
            if row.get("N") == "16" and row.get("policy") in POLICIES
        }
        paired_rows = {
            row["baseline"]: row
            for row in read_csv(pair["root"] / "main_multiseed_paired_lifts.csv")
            if row.get("N") == "16"
        }
        missing = [policy for policy in POLICIES if policy not in summary_rows]
        if missing:
            raise SystemExit(f"missing policies for {pair['name']}: {missing}")
        for baseline in ("NoSpec", "BestFixed"):
            if baseline not in paired_rows:
                raise SystemExit(f"missing paired lift {baseline} for {pair['name']}")
        detector_summary = {
            row["policy"]: row
            for row in read_csv(pair["detector_root"] / "processed" / "main_multiseed_summary.csv")
            if row.get("N") == "16"
        }
        detector_paired = {
            row["baseline"]: row
            for row in read_csv(pair["detector_root"] / "processed" / "main_multiseed_paired_lifts.csv")
            if row.get("N") == "16"
        }
        if "SpecSched-Safe" not in detector_summary or "NoSpec" not in detector_paired:
            raise SystemExit(f"missing detector rows for {pair['name']}")

        best = best_policy(summary_rows)
        best_fixed_policy = max(
            ["FixedK-1", "FixedK-3"],
            key=lambda policy: float(summary_rows[policy]["goodput_tok_s_mean"]),
        )
        nospec = fmt_mean_std(detector_summary["NoSpec"], "goodput_tok_s_mean", "goodput_tok_s_std")
        best_fixed = fmt_mean_std(summary_rows[best_fixed_policy], "goodput_tok_s_mean", "goodput_tok_s_std")
        tetris = fmt_mean_std(summary_rows["TETRIS-Proxy"], "goodput_tok_s_mean", "goodput_tok_s_std")
        specsched = fmt_mean_std(summary_rows["SpecSched"], "goodput_tok_s_mean", "goodput_tok_s_std")
        safe = fmt_mean_std(detector_summary["SpecSched-Safe"], "goodput_tok_s_mean", "goodput_tok_s_std")
        values = {
            "NoSpec": nospec,
            "BestFixed": best_fixed,
            "TETRIS-Proxy": tetris,
            "SpecSched": specsched,
            "SpecSched-Safe": safe,
        }
        if best == "FixedK-1" or best == "FixedK-3":
            values["BestFixed"] = f"\\textbf{{{values['BestFixed']}}}"
        elif best in values:
            values[best] = f"\\textbf{{{values[best]}}}"
        safe_lift = float(detector_paired["NoSpec"]["goodput_lift_pct_mean"])
        decision = detector_decision(pair)
        safe_lift_cell = color_lift(safe_lift, significant=safe_lift > 0.0)
        if abs(safe_lift) <= 5.0:
            safe_lift_cell = neutral_lift(safe_lift)
        pair_label = f"{pair['target'].split('-', 1)[1]} / {pair['draft'].split('-', 1)[1]}"

        lines.append(
            f"{pair['name']} & {pair_label} & "
            f"{values['NoSpec']} & {values['BestFixed']} & {values['TETRIS-Proxy']} & "
            f"{values['SpecSched']} & {values['SpecSched-Safe']} & {detector_cell(decision)} & "
            f"{safe_lift_cell} \\\\"
        )

    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\vspace{-0.5em}",
            "\\end{table*}",
            "",
        ]
    )
    return "\n".join(lines)


