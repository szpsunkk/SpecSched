#!/usr/bin/env python3
"""Generate scheduler-overhead table from the microbenchmark CSV."""
from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "results/scheduler_overhead_micro/processed/scheduler_all_summary.csv"
OUT = ROOT / "paper_assets/tables/scheduler_overhead.tex"


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def tag_kmax(tag: str, fallback: str) -> int:
    if tag.startswith("overhead_k"):
        return int(tag[len("overhead_k"):])
    return int(float(fallback))


def fmt_us(value: str) -> str:
    return f"{float(value):.1f}"


def fmt_pct(value: str) -> str:
    return f"{float(value) * 100.0:.2f}"


def heat_cell(value: str, minimum: float, maximum: float) -> str:
    number = float(value)
    if maximum <= minimum:
        shade = 5
    else:
        shade = int(round(5 + 35 * (number - minimum) / (maximum - minimum)))
    return f"\\heat{{{shade}}}{{{number:.1f}}}"


def build_table() -> str:
    if not SUMMARY.exists():
        raise SystemExit(f"missing {SUMMARY}; run the overhead microbenchmark first")
    rows = [
        row for row in read_csv(SUMMARY)
        if row.get("policy") == "SpecSched"
    ]
    if not rows:
        raise SystemExit(f"no SpecSched rows in {SUMMARY}")
    rows.sort(key=lambda row: (tag_kmax(row.get("tag", ""), row.get("x_kmax", "0")), int(float(row["N"]))))
    mean_values = [float(row["scheduler_cpu_mean_us"]) for row in rows]
    p95_values = [float(row["scheduler_policy_p95_us"]) for row in rows]
    lines = [
        "% Auto-generated by scripts/generate_scheduler_overhead_table.py. Do not edit values by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{CPU-side scheduler overhead microbenchmark on the 0.5B/0.5B local model pair. Values are microseconds per scheduling epoch; blue shading scales with overhead within this table.}",
        "\\label{tab:scheduler-overhead}",
        "\\small",
        "\\setlength{\\tabcolsep}{3.2pt}",
        "\\renewcommand{\\arraystretch}{1.12}",
        "\\begin{tabular}{rrrrr}",
        "\\toprule",
        "$k_{\\max}$ & $N$ & Mean ($\\mu$s) $\\downarrow$ & P95 policy ($\\mu$s) $\\downarrow$ & Wall (\\%) $\\downarrow$ \\\\",
        "\\midrule",
    ]
    last_k = None
    for row in rows:
        current_k = tag_kmax(row.get("tag", ""), row.get("x_kmax", "0"))
        if last_k is not None and current_k != last_k:
            lines.append("\\addlinespace")
        last_k = current_k
        lines.append(
            f"{current_k} & "
            f"{int(float(row['N']))} & "
            f"{heat_cell(row['scheduler_cpu_mean_us'], min(mean_values), max(mean_values))} & "
            f"{heat_cell(row['scheduler_policy_p95_us'], min(p95_values), max(p95_values))} & "
            f"{fmt_pct(row['scheduler_cpu_frac'])} \\\\"
        )
    lines.extend([
        "\\bottomrule",
        "\\end{tabular}",
        "\\vspace{-0.5em}",
        "\\end{table}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build_table(), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
