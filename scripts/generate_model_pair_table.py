def build_n32_table() -> str:
    lines = [
        "% Auto-generated by scripts/generate_model_pair_table.py. Do not edit values by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Additional $N=32$ model-pair boundary checks across three seeds. Values are SLO-aware goodput in tok/s ($\\uparrow$), mean$\\pm$std; the last column reports paired \\system{} lift against NoSpec.}",
        "\\label{tab:model-pair-n32}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.8pt}",
        "\\renewcommand{\\arraystretch}{1.12}",
        "\\begin{tabular}{@{}p{0.14\\columnwidth}p{0.24\\columnwidth}cccc@{}}",
        "\\toprule",
        "Family & Target / draft & NoSpec & TETRIS-Proxy & \\system{} & Lift \\\\",
        "\\midrule",
    ]
    for pair in n32_pair_roots():
        root = Path(pair["root"])
        summary_rows = {
            row["policy"]: row
            for row in read_csv(root / "main_multiseed_summary.csv")
            if row.get("N") == "32" and row.get("policy") in POLICIES
        }
        paired_rows = {
            row["baseline"]: row
            for row in read_csv(root / "main_multiseed_paired_lifts.csv")
            if row.get("N") == "32"
        }
        for policy in ("NoSpec", "TETRIS-Proxy", "SpecSched"):
            if policy not in summary_rows:
                raise SystemExit(f"missing policy {policy} for {pair['name']} N=32")
        if "NoSpec" not in paired_rows:
            raise SystemExit(f"missing NoSpec paired lift for {pair['name']} N=32")

        nospec = fmt_mean_std(summary_rows["NoSpec"], "goodput_tok_s_mean", "goodput_tok_s_std")
        tetris = fmt_mean_std(summary_rows["TETRIS-Proxy"], "goodput_tok_s_mean", "goodput_tok_s_std")
        specsched = fmt_mean_std(summary_rows["SpecSched"], "goodput_tok_s_mean", "goodput_tok_s_std")
        lift = float(paired_rows["NoSpec"]["goodput_lift_pct_mean"])
        lift_cell = color_lift(lift, significant=paired_rows["NoSpec"].get("ci95_positive") == "1")
        pair_label = f"{pair['target'].split('-', 1)[1]} / {pair['draft'].split('-', 1)[1]}"
        lines.append(
            f"{pair['name']} & {pair_label} & {nospec} & {tetris} & {specsched} & {lift_cell} \\\\"
        )

    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\vspace{-0.5em}",
            "\\end{table}",
            "",
        ]
    )
    return "\n".join(lines)


