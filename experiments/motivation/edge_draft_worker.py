"""JSONL draft-token worker for the Jetson edge device.

The cloud benchmark starts this script over SSH and keeps it alive. Each input
line is a JSON request:

    {"id": 1, "input_ids": [..], "k": 3}

The response is one JSON line containing greedy draft tokens generated by the
edge model. Status logs go to stderr so stdout remains machine-readable.
"""
import argparse
import json
import os
import sys
import time

os.environ.setdefault("USE_TF", "0")
os.environ.setdefault("USE_FLAX", "0")
os.environ.setdefault("TRANSFORMERS_NO_TF", "1")
os.environ.setdefault("TRANSFORMERS_NO_FLAX", "1")

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer


def resolve_snapshot(path):
    path = os.path.expanduser(path)
    snapshots = os.path.join(path, "snapshots")
    if os.path.isdir(snapshots):
        names = sorted(
            d for d in os.listdir(snapshots)
            if os.path.isdir(os.path.join(snapshots, d))
        )
        if names:
            return os.path.join(snapshots, names[0])
    return path


def log(message):
    print(message, file=sys.stderr, flush=True)


def load_model(path):
    model_path = resolve_snapshot(path)
    log(f"[edge] loading {model_path}")
    tok = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)
    model = AutoModelForCausalLM.from_pretrained(
        model_path,
        torch_dtype=torch.float16,
        attn_implementation="eager",
        trust_remote_code=True,
    ).to("cuda").eval()
    log(f"[edge] loaded params={sum(p.numel() for p in model.parameters())/1e6:.1f}M")
    return tok, model


@torch.inference_mode()
def warmup(model, vocab_size):
    ids = torch.randint(0, vocab_size, (1, 32), device="cuda")
    for _ in range(2):
        _ = model(input_ids=ids, use_cache=True)
    torch.cuda.synchronize()


@torch.inference_mode()
def draft_tokens(model, input_ids, k):
    ids = torch.tensor(input_ids, dtype=torch.long, device="cuda").view(1, -1)
    out = model(input_ids=ids, use_cache=True)
    past = out.past_key_values
    next_tok = out.logits[:, -1, :].argmax(dim=-1).view(1, 1)
    tokens = []
    for step in range(k):
        tokens.append(int(next_tok.item()))
        if step + 1 == k:
            break
        out = model(input_ids=next_tok, past_key_values=past, use_cache=True)
        past = out.past_key_values
        next_tok = out.logits[:, -1, :].argmax(dim=-1).view(1, 1)
    torch.cuda.synchronize()
    return tokens


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--model",
        default="~/.cache/huggingface/hub/models--Qwen--Qwen2.5-0.5B",
    )
    args = parser.parse_args()

    tok, model = load_model(args.model)
    warmup(model, tok.vocab_size)
    log("[edge] ready")

    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
            if req.get("cmd") == "stop":
                print(json.dumps({"ok": True, "stopped": True}), flush=True)
                break
            t0 = time.perf_counter()
            tokens = draft_tokens(model, req["input_ids"], int(req["k"]))
            elapsed_ms = (time.perf_counter() - t0) * 1000.0
            resp = {
                "ok": True,
                "id": req.get("id"),
                "tokens": tokens,
                "edge_elapsed_ms": elapsed_ms,
            }
        except Exception as exc:
            resp = {"ok": False, "id": req.get("id") if "req" in locals() else None, "error": repr(exc)}
        print(json.dumps(resp), flush=True)


if __name__ == "__main__":
    main()
