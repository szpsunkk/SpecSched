def build_baseline_table() -> str:
    main_summary = read_csv(ROOT / "results/tpds_multiseed_main/processed/main_multiseed_summary.csv")
    main_paired = read_csv(ROOT / "results/tpds_multiseed_main/processed/main_multiseed_paired_lifts.csv")
    eagle_paired = read_csv(ROOT / "results/eagle2_compare/processed/main_multiseed_paired_lifts.csv")

    main_by_policy = {
        (row["N"], row["policy"]): row
        for row in main_summary
        if row.get("N") in {"16", "32", "64"}
    }
    main_lifts = {
        (row["N"], row["baseline"]): float(row["goodput_lift_pct_mean"])
        for row in main_paired
        if row.get("N") in {"16", "32", "64"}
    }
    eagle_lifts = {
        (row["N"], row["baseline"]): float(row["goodput_lift_pct_mean"])
        for row in eagle_paired
        if row.get("N") in {"16", "32", "64"}
    }

    def paired_from(source: dict[tuple[str, str], float], baseline: str) -> list[float]:
        return [source[(n, baseline)] for n in ("16", "32", "64")]

    indep_lifts = []
    for n in ("16", "32", "64"):
        spec = float(main_by_policy[(n, "SpecSched")]["goodput_tok_s_mean"])
        base = float(main_by_policy[(n, "IndepOpt")]["goodput_tok_s_mean"])
        indep_lifts.append((spec / base - 1.0) * 100.0)

    rows: list[tuple[str, str, str, list[float], str]] = [
        (
            "NoSpec",
            "vLLM/PagedAttention~\\cite{kwon2023efficient}",
            "No-draft serving control",
            paired_from(main_lifts, "NoSpec"),
            "Clear gain over autoregressive serving.",
        ),
        (
            "BestFixed",
            "Speculative decoding~\\cite{leviathan2023fast,chen2023accelerating}",
            "Offline-tuned fixed-$k$ envelope",
            paired_from(main_lifts, "BestFixed"),
            "Statistically tied; all paired CIs cross zero.",
        ),
        (
            "IndepOpt",
            "Online draft control~\\cite{liu2024online,liu2024turbospec}",
            "Independent per-bucket draft choice",
            indep_lifts,
            "Aggregate lift from joint batching and cache control.",
        ),
        (
            "TETRIS-Proxy",
            "TETRIS~\\cite{wu2025tetris}",
            "Token-selection scheduler proxy",
            paired_from(main_lifts, "TETRIS-Proxy"),
            "Positive paired lift in this common executor.",
        ),
        (
            "EAGLE-2-Proxy",
            "EAGLE-2~\\cite{li2024eagle2}",
            "Dynamic draft-truncation proxy",
            paired_from(eagle_lifts, "EAGLE-2-Proxy"),
            "Lift over a truncation-only scheduling signal.",
        ),
        (
            "SpecServe-Proxy",
            "SpecServe/AdaSpec~\\cite{huang2025specserve}",
            "SLO-slack adaptive proxy",
            paired_from(eagle_lifts, "SpecServe-Proxy"),
            "Lift under the same SLO calibration.",
        ),
    ]

    lines = [
        "% Auto-generated by scripts/generate_model_pair_table.py. Do not edit values by hand.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Core baseline comparison under the common executor. Values are paired \\system{} SLO-goodput lift at $N=16/32/64$ on Qwen2.5-7B/0.5B. Baseline names appear first, followed by their reference source. Proxy rows isolate scheduler-visible signals and are not native-system reproductions.}",
        "\\label{tab:baseline-performance}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.8pt}",
        "\\renewcommand{\\arraystretch}{1.12}",
        "\\resizebox{\\columnwidth}{!}{%",
        "\\begin{tabular}{@{}p{0.39\\columnwidth}ccc@{}}",
        "\\toprule",
        "\\multirow{2}{*}{Baseline / comparator with source} &",
        "\\multicolumn{3}{c}{\\system{} SLO-goodput lift ($\\uparrow$)} \\\\",
        "\\cmidrule(lr){2-4}",
        " & $N=16$ & $N=32$ & $N=64$ \\\\",
        "\\midrule",
    ]
    for name, reference, role, lifts, interpretation in rows:
        n16, n32, n64 = [
            neutral_lift(value) if name == "BestFixed" else color_lift(value)
            for value in lifts
        ]
        row_prefix = "\\rowcolor{tabgray}" if name == "BestFixed" else ""
        lines.append(
            f"{row_prefix}{name}, {reference} & {n16} & {n32} & {n64} \\\\"
        )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "}",
            "\\vspace{-0.5em}",
            "\\end{table}",
            "",
        ]
    )
    return "\n".join(lines)


def maybe_build_pressure_table() -> str | None:
    required = []
    for pair in pressure_roots():
        required.append(Path(pair["kv_root"]) / "main_multiseed_summary.csv")
        required.append(Path(pair["slo_root"]) / "main_multiseed_paired_lifts.csv")
    if not all(path.exists() for path in required):
        return None

    lines = [
        "% Auto-generated by scripts/generate_model_pair_table.py. Do not edit values by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Additional $N=32$ model-pair pressure checks across three seeds. KV rows report SLO-aware goodput in tok/s ($\\uparrow$); SLO rows report paired \\system{} lift over NoSpec with 95\\% confidence intervals.}",
        "\\label{tab:model-pair-pressure}",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{2.2pt}",
        "\\renewcommand{\\arraystretch}{1.12}",
        "\\begin{tabular}{@{}p{0.10\\textwidth}p{0.11\\textwidth}p{0.12\\textwidth}p{0.18\\textwidth}p{0.16\\textwidth}p{0.11\\textwidth}p{0.08\\textwidth}@{}}",
        "\\toprule",
        "Family & Stressor & Setting & \\system{} result & Best / reference & Lift or gap & Evidence \\\\",
        "\\midrule",
        "\\multicolumn{7}{@{}l}{\\textit{KV-pressure: best eviction variant can change with pair and budget}} \\\\",
        "\\cmidrule(l){1-7}",
    ]
    pairs = pressure_roots()
    for pair in pairs:
        kv_rows = read_csv(Path(pair["kv_root"]) / "main_multiseed_summary.csv")
        for budget in ("256", "512"):
            group = [
                row for row in kv_rows
                if row.get("N") == "32" and row.get("configured_kv_blocks") == budget
            ]
            by_policy = {row["policy"]: row for row in group}
            spec = by_policy.get("SpecSched")
            if not spec:
                raise SystemExit(f"missing SpecSched KV row for {pair['name']} budget={budget}")
            alternatives = [
                row for policy, row in by_policy.items()
                if policy != "SpecSched"
            ]
            if not alternatives:
                raise SystemExit(f"missing KV alternatives for {pair['name']} budget={budget}")
            best = max(alternatives, key=lambda row: float(row["goodput_tok_s_mean"]))
            spec_gp = float(spec["goodput_tok_s_mean"])
            best_gp = float(best["goodput_tok_s_mean"])
            gap = (spec_gp / best_gp - 1.0) * 100.0 if best_gp > 0 else 0.0
            lines.append(
                f"{pair['name']} & KV budget & {budget} blocks & "
                f"{fmt_mean_std(spec, 'goodput_tok_s_mean', 'goodput_tok_s_std')} & "
                f"{best['policy']} {fmt_mean_std(best, 'goodput_tok_s_mean', 'goodput_tok_s_std')} & "
                f"{color_lift(gap, significant=False)} & goodput \\\\"
            )

    lines.extend([
        "\\midrule",
        "\\multicolumn{7}{@{}l}{\\textit{SLO-pressure: detector decision follows the sign of paired CI}} \\\\",
        "\\cmidrule(l){1-7}",
    ])
    for pair in pairs:
        slo_lifts = read_csv(Path(pair["slo_root"]) / "main_multiseed_paired_lifts.csv")
        for beta in ("1.25", "2.0"):
            row = next(
                (
                    item for item in slo_lifts
                    if item.get("N") == "32"
                    and item.get("configured_beta") == beta
                    and item.get("baseline") == "NoSpec"
                ),
                None,
            )
            if not row:
                raise SystemExit(f"missing SLO lift for {pair['name']} beta={beta}")
            lift = float(row["goodput_lift_pct_mean"])
            lo = float(row["goodput_lift_pct_ci95_low"])
            hi = float(row["goodput_lift_pct_ci95_high"])
            interval = f"[{lo:+.1f}\\%, {hi:+.1f}\\%]"
            if lift < 0:
                interval = interval.replace("-", "$-$")
                lift_cell = color_lift(lift, significant=False)
                action = "\\dOFF{OFF}"
            else:
                lift_cell = color_lift(lift, significant=True)
                action = "\\dON{ON}"
            lines.append(
                f"{pair['name']} & SLO multiplier & $\\beta={beta}$ & "
                f"{lift_cell} & NoSpec & "
                f"{interval} & {action} \\\\"
            )

    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\vspace{-0.5em}",
            "\\end{table*}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build_table(), encoding="utf-8")
    OUT_N32.write_text(build_n32_table(), encoding="utf-8")
    OUT_BASELINE.write_text(build_baseline_table(), encoding="utf-8")
    pressure_table = maybe_build_pressure_table()
    if pressure_table is not None:
        OUT_PRESSURE.write_text(pressure_table, encoding="utf-8")
        print(f"wrote {OUT_PRESSURE}")
    print(f"wrote {OUT_BASELINE}")
    print(f"wrote {OUT}")
    print(f"wrote {OUT_N32}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
